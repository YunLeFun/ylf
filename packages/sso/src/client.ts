/**
 * `@yunlefun/sso` —— 子应用侧 SSO 客户端（浏览器环境）。
 *
 * 让任意前端「用云乐坊账号一处登录、各站免登」：打开主站桥接页、安全校验回传消息、
 * 把 CloudBase session 注入子应用自己的 SDK。详见 https://docs.yunle.fun 的 SSO 接入指南。
 */
import type { NativeSsoOptions } from './native'
import type { SsoMode, SsoRedirectResult, SsoResult, SsoSession } from './protocol'
import { isInYunleApp, requestSsoNative } from './native'
import { buildSsoRequestUrl, deriveSsoPkceChallenge, hasSsoRedirectResult, isSsoPkceVerifier, parseSsoRedirectResult, parseSsoResultMessage, readSsoReturnUrl } from './protocol'

/** 主站默认源 */
export const YLF_DEFAULT_SSO_ORIGIN = 'https://www.yunle.fun'

/** Default HTTPS endpoint that atomically redeems a v2 SSO authorization code. */
export const YLF_DEFAULT_SSO_EXCHANGE_URL = 'https://api.yunle.fun/sso-ticket'

export interface SsoOptions {
  /** 主站源，默认 https://www.yunle.fun。本地联调可传 http://localhost:5173 等 */
  ssoOrigin?: string
  /** silent（默认）：隐藏 iframe 静默探测；interactive：弹窗，未登录时引导登录 */
  mode?: SsoMode
  /** 超时毫秒数。默认 silent 8000、interactive 120000 */
  timeoutMs?: number
  /** Explicit loopback-only HTTP exception for local development. */
  allowHttpLocalhost?: boolean
  /** One-time code exchange endpoint. Defaults to the YunLeFun production endpoint. */
  exchangeUrl?: string
  /** 云乐坊原生容器内的选项（仅 isInYunleApp() 为真时生效） */
  native?: NativeSsoOptions
}

/** Minimal CloudBase auth surface accepted by the SSO adoption helpers. */
export interface SsoAdoptionAuth {
  /** Legacy session adoption. New consumers must not provide main-site refresh tokens. */
  setSession?: (params: { access_token: string, refresh_token: string }) => Promise<unknown>
  /**
   * 可选：CloudBase `signInWithCustomTicket`。提供且桥接下发了一次性 `ticket` 时，
   * `signInWithSso` / `adoptSsoResult` 会优先用它换取**子站自己的独立会话**（独立
   * refresh_token、同源可续期），而非复用主站会话 `setSession`。
   *
   * 注意：CloudBase js-sdk **v2** 的签名是接收一个**返回票据的函数**（`getTickFn`），
   * 不是票据字符串本身——传字符串会被当函数调用而同步抛错。
   */
  signInWithCustomTicket?: (getTicket: () => Promise<string>) => Promise<unknown>
}

/** Legacy auth surface required only by {@link adoptSession}. */
export interface SsoSetSessionAuth extends SsoAdoptionAuth {
  setSession: (params: { access_token: string, refresh_token: string }) => Promise<unknown>
}

/** Fetch-compatible function seam used by code exchange and deterministic tests. */
export type SsoFetch = (input: RequestInfo | URL, init?: RequestInit) => Promise<Response>

/** Options for exchanging a bound one-time SSO authorization code. */
export interface SsoCodeExchangeOptions {
  nonce: string
  /** Secret PKCE verifier generated by the consumer. Never put it in a URL. */
  codeVerifier: string
  exchangeUrl?: string
  allowHttpLocalhost?: boolean
  fetch?: SsoFetch
}

function createNonce(): string {
  const bytes = new Uint8Array(16)
  crypto.getRandomValues(bytes)
  return Array.from(bytes, b => b.toString(16).padStart(2, '0')).join('')
}

function createPkceVerifier(): string {
  const bytes = new Uint8Array(32)
  crypto.getRandomValues(bytes)
  return Array.from(bytes, byte => byte.toString(16).padStart(2, '0')).join('')
}

/**
 * 向主站发起一次 SSO 请求，拿回（或确认拿不到）登录态。
 * 不直接登录子应用，只负责取 session；注入交给 {@link adoptSession} / {@link signInWithSso}。
 */
export async function requestSso(options: SsoOptions = {}): Promise<SsoResult> {
  if (typeof window === 'undefined' || typeof document === 'undefined')
    return { ok: false, reason: 'error' }

  const ssoOrigin = (options.ssoOrigin ?? YLF_DEFAULT_SSO_ORIGIN).replace(/\/+$/, '')
  const mode = options.mode ?? 'silent'
  const timeoutMs = options.timeoutMs ?? (mode === 'interactive' ? 120_000 : 8000)
  const nonce = createNonce()
  const codeVerifier = createPkceVerifier()
  const codeChallenge = await deriveSsoPkceChallenge(codeVerifier)
  const url = buildSsoRequestUrl({
    ssoOrigin,
    mode,
    targetOrigin: window.location.origin,
    nonce,
    codeChallenge,
    allowHttpLocalhost: options.allowHttpLocalhost,
  })

  return new Promise<SsoResult>((resolve) => {
    let settled = false
    let frame: HTMLIFrameElement | null = null
    let popup: Window | null = null
    let timer: ReturnType<typeof setTimeout> | null = null
    let closedPoll: ReturnType<typeof setInterval> | null = null

    function cleanup() {
      window.removeEventListener('message', onMessage)
      if (timer)
        clearTimeout(timer)
      if (closedPoll)
        clearInterval(closedPoll)
      if (frame?.parentNode)
        frame.parentNode.removeChild(frame)
      if (popup && !popup.closed)
        popup.close()
    }

    function settle(result: SsoResult) {
      if (settled)
        return
      settled = true
      cleanup()
      resolve(result)
    }

    function onMessage(event: MessageEvent) {
      // 发起窗口校验：消息必须来自我们打开的 iframe / 弹窗本身
      const expectedSource = popup ?? frame?.contentWindow ?? null
      if (expectedSource && event.source !== expectedSource)
        return

      const result = parseSsoResultMessage({
        expectedOrigin: ssoOrigin,
        expectedNonce: nonce,
        eventOrigin: event.origin,
        data: event.data,
      })
      if (result) {
        settle(result.ok && 'code' in result
          ? { ...result, codeVerifier }
          : result)
      }
    }

    window.addEventListener('message', onMessage)
    timer = setTimeout(() => settle({ ok: false, reason: 'timeout' }), timeoutMs)

    if (mode === 'interactive') {
      popup = window.open(url, 'ylf-sso', 'width=480,height=640,menubar=no,toolbar=no,location=yes')
      if (!popup) {
        settle({ ok: false, reason: 'popup_blocked' })
        return
      }
      // 用户主动关闭弹窗时及时结束等待
      closedPoll = setInterval(() => {
        if (popup?.closed)
          settle({ ok: false, reason: 'closed' })
      }, 400)
    }
    else {
      frame = document.createElement('iframe')
      frame.setAttribute('aria-hidden', 'true')
      frame.title = 'YunLeFun SSO'
      frame.style.cssText = 'position:absolute;top:0;left:0;width:0;height:0;border:0;visibility:hidden;'
      frame.src = url
      document.body.appendChild(frame)
    }
  })
}

/**
 * 把主站回传的 session 注入子应用自己的 CloudBase SDK。
 * setSession 只需要 access_token + refresh_token；注入后子应用即变为登录态，uid 与主站一致。
 * @returns 是否成功注入（缺少必要 token 时返回 false）
 */
export async function adoptSession(
  auth: SsoSetSessionAuth,
  session: SsoSession,
): Promise<boolean> {
  if (!session.access_token || !session.refresh_token)
    return false
  await auth.setSession({
    access_token: session.access_token,
    refresh_token: session.refresh_token,
  })
  return true
}

/**
 * 注入登录态：优先用桥接下发的一次性 `ticket` 走 `signInWithCustomTicket`（换取子站
 * 自己的独立可续期会话），否则回退到 `setSession`（复用主站会话）。
 *
 * 是 {@link signInWithSso} 的内部采用步骤，也单独导出，供「自行发 {@link requestSso}、
 * 自行采用会话」的子应用（如改用 `setCredentials` 适配的站点）复用同一套优先级。
 * @returns 是否成功注入
 */
export async function adoptSsoResult(
  auth: SsoAdoptionAuth,
  result: Extract<SsoResult, { ok: true }>,
  options: Omit<SsoCodeExchangeOptions, 'codeVerifier' | 'nonce'> = {},
): Promise<boolean> {
  if ('code' in result) {
    if (!result.codeVerifier)
      return false
    return adoptSsoCode(auth, result.code, {
      ...options,
      nonce: result.nonce,
      codeVerifier: result.codeVerifier,
    })
  }
  if (result.ticket && typeof auth.signInWithCustomTicket === 'function') {
    // v2 API：传一个返回票据的函数，不是票据字符串。
    const ticket = result.ticket
    await auth.signInWithCustomTicket(() => Promise.resolve(ticket))
    return true
  }
  return typeof auth.setSession === 'function'
    ? adoptSession(auth as SsoSetSessionAuth, result.session)
    : false
}

/**
 * Atomically redeem a v2 authorization code, then hand the transient CloudBase ticket directly
 * to the official SDK. The exchange response is rejected if it contains session tokens.
 */
export async function adoptSsoCode(
  auth: SsoAdoptionAuth,
  code: string,
  options: SsoCodeExchangeOptions,
): Promise<boolean> {
  if (!/^[\w-]{43}$/.test(code) || !/^[\w-]{32,128}$/.test(options.nonce) || !isSsoPkceVerifier(options.codeVerifier))
    return false
  if (typeof auth.signInWithCustomTicket !== 'function')
    return false
  const exchangeUrl = readSsoReturnUrl(
    options.exchangeUrl ?? YLF_DEFAULT_SSO_EXCHANGE_URL,
    { allowHttpLocalhost: options.allowHttpLocalhost },
  )
  if (!exchangeUrl)
    throw new TypeError('SSO exchange URL must use HTTPS')
  const fetchImpl = options.fetch ?? globalThis.fetch
  if (typeof fetchImpl !== 'function')
    throw new TypeError('fetch is unavailable')
  await auth.signInWithCustomTicket(async () => {
    const response = await fetchImpl(exchangeUrl, {
      method: 'POST',
      credentials: 'omit',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ action: 'exchangeSsoCode', code, nonce: options.nonce, codeVerifier: options.codeVerifier }),
    })
    const payload = await response.json() as unknown
    if (!response.ok || !isTicketExchangeResponse(payload))
      throw new Error('SSO authorization code exchange failed')
    return payload.ticket
  })
  return true
}

function isTicketExchangeResponse(value: unknown): value is { ok: true, ticket: string } {
  if (value === null || typeof value !== 'object' || Array.isArray(value))
    return false
  const record = value as Record<string, unknown>
  return record.ok === true
    && typeof record.ticket === 'string'
    && record.ticket.length > 0
    && !('access_token' in record)
    && !('refresh_token' in record)
    && !('session' in record)
}

/**
 * 一站式：发起 SSO 并在成功后直接注入子应用登录态。是大多数子应用唯一需要调用的函数。
 *
 * 自动选路：在云乐坊原生容器内（{@link isInYunleApp}）走 `window.ylf` 桥取会话；
 * 否则走 www.yunle.fun 的 postMessage 桥。注入优先用一次性 `ticket`（子站独立会话），
 * 否则回退到 `setSession`，调用方无需感知平台或凭证形态。
 */
export async function signInWithSso(
  auth: SsoAdoptionAuth,
  options: SsoOptions = {},
): Promise<SsoResult> {
  const result = isInYunleApp()
    ? await requestSsoNative(options.native)
    : await requestSso(options)
  if (result.ok) {
    const adopted = await adoptSsoResult(auth, result, {
      exchangeUrl: options.exchangeUrl,
      allowHttpLocalhost: options.allowHttpLocalhost,
    })
    if (!adopted)
      return { ok: false, reason: 'not_authenticated' }
  }
  return result
}

// ──────────────────────────── 重定向握手（业界标准，抗存储分区）────────────────────────────

const REDIRECT_NONCE_KEY = 'ylf:sso:redirect-nonce'
const REDIRECT_PKCE_VERIFIER_KEY = 'ylf:sso:redirect-pkce-verifier'

export interface RedirectSsoOptions {
  /** 主站源，默认 https://www.yunle.fun */
  ssoOrigin?: string
  /**
   * 登录完成后回跳的地址，默认当前页（去掉已有 hash，避免与回传 fragment 冲突）。
   * 其 origin 必须在主站 SSO 白名单内，否则桥接页会拒绝跳转。
   */
  returnUrl?: string
  /** Explicit loopback-only HTTP exception for local development. */
  allowHttpLocalhost?: boolean
}

/**
 * 发起**顶层重定向**式 SSO（业界标准的抗存储分区方案）：整页跳到主站桥接页，登录确认后
 * 桥接页带绑定 origin + nonce 的一次性授权码跳回 `returnUrl`。本函数让页面导航走人、不会 resolve；回跳后在应用
 * 启动时调用 {@link consumeSsoRedirect} 取结果。
 *
 * 相比 {@link requestSso} 的隐藏 iframe / 弹窗：重定向每一跳都是第一方上下文，因此在
 * Safari ITP / 隐私模式等第三方存储被分区的环境里也能完成握手。
 */
export async function startSsoRedirect(options: RedirectSsoOptions = {}): Promise<void> {
  if (typeof window === 'undefined')
    return
  const ssoOrigin = (options.ssoOrigin ?? YLF_DEFAULT_SSO_ORIGIN).replace(/\/+$/, '')
  const nonce = createNonce()
  const codeVerifier = createPkceVerifier()
  const codeChallenge = await deriveSsoPkceChallenge(codeVerifier)
  const { origin, pathname, search } = window.location
  const returnUrl = options.returnUrl ?? `${origin}${pathname}${search}`
  try {
    window.sessionStorage.setItem(REDIRECT_NONCE_KEY, nonce)
    window.sessionStorage.setItem(REDIRECT_PKCE_VERIFIER_KEY, codeVerifier)
  }
  catch {
    // sessionStorage 不可用（隐私模式等）：仍可发起，但回跳会因无法校验 nonce 而被忽略；
    // 调用方应保留 popup / iframe 兜底。
  }
  window.location.assign(buildSsoRequestUrl({
    ssoOrigin,
    mode: 'redirect',
    targetOrigin: origin,
    nonce,
    codeChallenge,
    returnUrl,
    allowHttpLocalhost: options.allowHttpLocalhost,
  }))
}

/**
 * 在应用启动时调用：若当前 URL 是一次 SSO 重定向回跳，解析并返回结果，同时**清理地址栏与暂存 nonce**
 * （避免一次性授权码残留在历史/地址栏）。不是回跳（或 nonce 不匹配）则返回 null。
 * 成功后用 {@link adoptSsoCode} 原子兑换授权码并采用登录态。
 */
export function consumeSsoRedirect(): SsoRedirectResult | null {
  if (typeof window === 'undefined')
    return null
  const { hash } = window.location
  if (!hash || !hasSsoRedirectResult(hash))
    return null

  let expectedNonce = ''
  let codeVerifier = ''
  try {
    expectedNonce = window.sessionStorage.getItem(REDIRECT_NONCE_KEY) ?? ''
    codeVerifier = window.sessionStorage.getItem(REDIRECT_PKCE_VERIFIER_KEY) ?? ''
  }
  catch {
    expectedNonce = ''
  }

  const result = parseSsoRedirectResult({ hash, expectedNonce })

  try {
    window.sessionStorage.removeItem(REDIRECT_NONCE_KEY)
    window.sessionStorage.removeItem(REDIRECT_PKCE_VERIFIER_KEY)
  }
  catch {}
  stripRedirectHash()

  if (result?.ok && isSsoPkceVerifier(codeVerifier))
    return { ...result, codeVerifier }
  return result?.ok ? null : result
}

/** @deprecated Legacy postMessage providers may still expose a ticket; redirect consumers must use {@link adoptSsoCode}. */
export async function adoptSsoTicket(auth: SsoSetSessionAuth, ticket: string): Promise<boolean> {
  if (!ticket || typeof auth.signInWithCustomTicket !== 'function')
    return false
  // v2 API：传一个返回票据的函数，不是票据字符串。
  await auth.signInWithCustomTicket(() => Promise.resolve(ticket))
  return true
}

function stripRedirectHash(): void {
  const { origin, pathname, search } = window.location
  const clean = `${origin}${pathname}${search}`
  try {
    window.history.replaceState(window.history.state, '', clean)
  }
  catch {
    window.location.hash = ''
  }
}
